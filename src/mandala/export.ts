import type { ResolvedFeatures } from '../features/types';
import type { TrackMeta } from '../spotify/api';
import { drawPrims } from './render';
import { sectionAngles, type RingSpec } from './rings';
import { buildScene } from './scene';
import { primsToSvg } from './svg';
import { buildWavesScene } from './waves';
import type { ViewMode } from '../lib/url';

export const EXPORT_BACKGROUND = '#05060a';

export interface ExportInput {
  rings: RingSpec[];
  features: ResolvedFeatures;
  track: TrackMeta;
  t: number; // seconds — the moment to freeze
  transparent: boolean;
  /** Which view to export; defaults to the mandala. */
  view?: ViewMode;
  size?: number;
}

/** Export canvas size: square for the mandala, 16:10 for the waves. */
function exportSize(input: ExportInput, base: number) {
  const w = input.size ?? base;
  return input.view === 'waves' ? { w, h: Math.round(w * 0.625) } : { w, h: w };
}

function primsFor(input: ExportInput, w: number, h: number, samples: number) {
  if (input.view === 'waves') {
    const ts = w / 1100;
    const pad = 28 * ts;
    return buildWavesScene(input.rings, {
      width: w,
      height: h,
      t: input.t,
      keyPitchClass: input.features.key,
      focusId: null,
      inset: { top: pad, bottom: pad, left: pad, right: pad },
      labels: true,
      textScale: ts,
      samples,
    }).prims;
  }
  return sceneFor(input, w, samples).prims;
}

function sceneFor(input: ExportInput, size: number, samples: number) {
  return buildScene(input.rings, {
    width: size,
    height: size,
    t: input.t,
    durationSec: input.track.durationMs / 1000,
    sectionAngles: sectionAngles(input.features, input.track.durationMs / 1000),
    keyPitchClass: input.features.key,
    focusId: null,
    samples,
  });
}

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60) || 'mandala';

const stamp = (t: number) => `${Math.floor(t / 60)}m${String(Math.floor(t % 60)).padStart(2, '0')}s`;

export function exportFileName(track: TrackMeta, t: number, ext: string, view: ViewMode = 'mandala') {
  return `${slug(`${track.artists[0] ?? ''} ${track.name}`)}-${view === 'waves' ? 'waves-' : ''}${stamp(t)}.${ext}`;
}

function download(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function buildSvg(input: ExportInput): string {
  const { w, h } = exportSize(input, input.view === 'waves' ? 1600 : 2048);
  const view = input.view === 'waves' ? 'Waves' : 'Mandala';
  return primsToSvg(primsFor(input, w, h, 1440), w, h, {
    background: input.transparent ? null : EXPORT_BACKGROUND,
    title: `Harmonic Mandala (${view}) — ${input.track.name}`,
    description: `${input.track.artists.join(', ')} · ${input.track.name} at ${stamp(input.t)}. Generated by Harmonic Mandala.`,
  });
}

export function exportSvg(input: ExportInput) {
  download(new Blob([buildSvg(input)], { type: 'image/svg+xml' }), exportFileName(input.track, input.t, 'svg', input.view));
}

export async function exportPng(input: ExportInput) {
  const { w, h } = exportSize(input, input.view === 'waves' ? 3200 : 3072);
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  if (!ctx) throw new Error('Canvas 2D is unavailable in this browser.');
  drawPrims(ctx, primsFor(input, w, h, 2048), w, h, input.transparent ? null : EXPORT_BACKGROUND);
  const blob = await new Promise<Blob | null>((res) => canvas.toBlob(res, 'image/png'));
  if (!blob) throw new Error('PNG encoding failed.');
  download(blob, exportFileName(input.track, input.t, 'png', input.view));
}
